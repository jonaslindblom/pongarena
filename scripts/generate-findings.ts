import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const root = new URL('../', import.meta.url)
const comparisonPath = 'experiments/quill-training/current-comparison.json'
const planPath = 'experiments/quill-training/current-comparison-plan.json'
const followUpPath = 'experiments/one-prompt-weights/follow-up/results/'
const outputPath = 'src/findingsData.ts'
const hash = (bytes: string | Uint8Array) => createHash('sha256').update(bytes).digest('hex')
const read = (path: string) => readFile(new URL(path, root), 'utf8')

interface Result {
  model: string
  opponent: string
  rally_score: number
  rally_score_ci95: [number, number]
  league_score: number
  league_score_ci95: [number, number]
  wins: number
  draws: number
  losses: number
  contest_wins: number
  contest_draws: number
  contest_losses: number
}

interface PromptResult {
  candidate: { sha256: string }
  matchups: {
    opponent: { id: string; sha256: string }
    record: { played: number; leaguePoints: number; rallyPointsFor: number }
  }[]
}

export async function findingsSource() {
  const [comparisonText, planText] = await Promise.all([read(comparisonPath), read(planPath)])
  const comparison = JSON.parse(comparisonText)
  const plan = JSON.parse(planText)
  if (JSON.stringify(comparison.plan) !== JSON.stringify(plan)) throw new Error('Findings comparison does not match its frozen plan.')
  for (const model of plan.models) {
    if (hash(await readFile(new URL(`public/models/${model.id}.onnx`, root))) !== model.sha256)
      throw new Error(`Findings data is stale for ${model.id}. Run a new frozen comparison.`)
  }
  const directed = (row: Result, reverse = false) => ({
    model: reverse ? row.opponent : row.model,
    opponent: reverse ? row.model : row.opponent,
    rallyScore: reverse ? 1 - row.rally_score : row.rally_score,
    rallyScoreCi95: reverse ? row.rally_score_ci95.map(value => 1 - value).reverse() : row.rally_score_ci95,
    leagueScore: reverse ? 1 - row.league_score : row.league_score,
    leagueScoreCi95: reverse ? row.league_score_ci95.map(value => 1 - value).reverse() : row.league_score_ci95,
    wins: reverse ? row.losses : row.wins, draws: row.draws, losses: reverse ? row.wins : row.losses,
    contestWins: reverse ? row.contest_losses : row.contest_wins,
    contestDraws: row.contest_draws,
    contestLosses: reverse ? row.contest_wins : row.contest_losses,
  })
  const findingsData = {
    rulesId: plan.rules_id, contractId: plan.contract_id,
    pairedServeSets: plan.seeds.length,
    ralliesPerMatchup: plan.seeds.length * plan.rallies_per_side * 2,
    planSha256: hash(planText), sourceSha256: hash(comparisonText),
    models: plan.models,
    matchups: (comparison.matchups as Result[]).flatMap(row => [directed(row), directed(row, true)]),
  }
  const promptModels = ['rules-163-a', 'rules-163-b', 'tactical-163-a', 'tactical-163-b']
  const labels = ['Rules only · run 1', 'Rules only · run 2', 'Rules + brief · run 1 (OneShot)', 'Rules + brief · run 2']
  const opponents = ['follow', 'small', 'predict', 'attack', 'counter', 'quill', 'large']
  const promptResults: PromptResult[] = await Promise.all(promptModels.map(async id => JSON.parse(await read(followUpPath + id + '.json'))))
  for (const report of promptResults) {
    for (const match of report.matchups) {
      if (match.record.played !== 64) throw new Error('The prompt experiment uses 64 paired serve sets.')
      if (hash(await readFile(new URL(`public/models/${match.opponent.id}.onnx`, root))) !== match.opponent.sha256)
        throw new Error(`Prompt findings are stale for ${match.opponent.id}. Replay its saved responses.`)
    }
  }
  if (promptResults[2].candidate.sha256 !== plan.models.find((model: { id: string }) => model.id === 'oneshot')?.sha256)
    throw new Error('OneShot must remain the saved Tactical A response.')
  const oneShotResults = promptResults.map((report, index) => ({ label: labels[index],
    points: opponents.map(opponent => report.matchups.find(row => row.opponent.id === opponent)!.record.leaguePoints) }))
  const oneShotRalliesAgainstLarge = promptResults[2].matchups.find(row => row.opponent.id === 'large')!.record.rallyPointsFor
  return '// Generated by scripts/generate-findings.ts from frozen comparisons and saved prompt replies.\n'
    + '// Replay instructions: experiments/quill-training/README.md and experiments/one-prompt-weights/follow-up/README.md.\n'
    + `export const findingsData = ${JSON.stringify(findingsData, null, 2)} as const\n\n`
    + '// Paired league points out of 64: Follow, Small, Predict, Attack, Counter, Quill, Large.\n'
    + `export const oneShotResults = ${JSON.stringify(oneShotResults, null, 2)} as const\n\n`
    + `export const oneShotRalliesAgainstLarge = ${oneShotRalliesAgainstLarge}\n`
}

async function main() {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node --import tsx scripts/generate-findings.ts [--check]')
  const source = await findingsSource()
  if (process.argv.includes('--check')) {
    if (await read(outputPath) !== source) throw new Error('Findings display data is stale. Run node --import tsx scripts/generate-findings.ts.')
    console.log('Verified Findings display data against frozen results and current model bytes.')
  } else {
    await writeFile(new URL(outputPath, root), source)
    console.log(`Generated ${outputPath}`)
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(error => { console.error(error instanceof Error ? error.message : error); process.exitCode = 1 })
}
